Masters(MappingType,TargetId,ActualTargetCode,TargetName,ActiveState) AS
(
    SELECT CONVERT(nvarchar(40),l.Type),l.Id,CONVERT(nvarchar(200),l.Code),
           CONVERT(nvarchar(500),l.Value),
           CASE WHEN l.IsActive=1 THEN N'Active' ELSE N'Inactive' END
    FROM Config.SystemLookups l
    WHERE l.Type IN (N'CustomerGroup',N'SupplierGroup',N'PaymentTerm',N'PriceLevel')
    UNION ALL
    SELECT N'Warehouse',w.Id,w.Code,w.Name,
           CASE WHEN w.IsActive=1 THEN N'Active' ELSE N'Inactive' END
    FROM Master.Warehouses w
    UNION ALL
    SELECT N'Unit',u.Id,u.Symbol,u.Name,N'No active flag'
    FROM Master.UnitOfMeasures u
    UNION ALL
    SELECT N'Category',c.Id,c.Code,c.Name,N'Check posting account in result 8'
    FROM Master.Categories c
    UNION ALL
    SELECT N'Brand',b.Id,b.Name,b.Name,N'No active flag'
    FROM Master.Brands b
    UNION ALL
    SELECT N'Stock',v.Id,v.SKU,v.Name,
           CASE WHEN v.IsActive=1 THEN N'Active' ELSE N'Inactive' END
    FROM Master.ProductVariants v
    UNION ALL
    SELECT N'BankBranch',br.Id,CONCAT(b.BankCode,N'-',br.BranchCode),
           CONCAT(b.Name,N' / ',br.BranchName),
           CASE WHEN br.IsActive=1 AND b.IsActive=1 THEN N'Active' ELSE N'Inactive' END
    FROM Finance.BankBranches br JOIN Finance.Banks b ON b.Id=br.BankId
)
SELECT N'6_MAPPING_IDS' AS ResultSet, r.MappingType,r.LegacyCode,
       r.ExpectedTargetCode,m.TargetId,m.ActualTargetCode,m.TargetName,m.ActiveState,
       COUNT(m.TargetId) OVER(PARTITION BY r.MappingType,r.LegacyCode) AS CandidateCount,
       CASE WHEN m.TargetId IS NULL THEN N'MISSING'
            WHEN COUNT(m.TargetId) OVER(PARTITION BY r.MappingType,r.LegacyCode)>1
                 THEN N'AMBIGUOUS'
            WHEN m.ActiveState=N'Inactive' THEN N'INACTIVE'
            WHEN r.MappingType=N'Stock' AND
                 r.ExpectedTargetCode COLLATE Latin1_General_100_BIN2 <>
                 m.ActualTargetCode COLLATE Latin1_General_100_BIN2
                 THEN N'REVIEW SKU CASE'
            ELSE N'MATCH' END AS CheckResult
FROM Requested r LEFT JOIN Masters m
  ON m.MappingType=r.MappingType
 AND UPPER(LTRIM(RTRIM(m.ActualTargetCode)))=UPPER(r.ExpectedTargetCode)
ORDER BY r.MappingType,r.LegacyCode,m.TargetId;

