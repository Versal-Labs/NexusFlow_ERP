-- NexusFlow pilot mapping-ID discovery. READ ONLY: no data/schema changes.
-- Run in Azure Data Studio against versalapps.database.windows.net / NexusGarnetProd.
-- Return ALL result grids. No password or connection string is requested.
-- This file identifies destination IDs; local test database IDs are not portable.
SET NOCOUNT ON;
SET LOCK_TIMEOUT 15000;
SET DEADLOCK_PRIORITY LOW;

DECLARE @ExpectedDatabase sysname = N'NexusGarnetProd';
DECLARE @ExpectedServer sysname = N'versalapps';

IF DB_NAME() <> @ExpectedDatabase
    THROW 51000, 'Wrong database. Select NexusGarnetProd before running this check.', 1;
IF LOWER(CONVERT(nvarchar(128),SERVERPROPERTY('ServerName')))
       NOT IN (@ExpectedServer, @ExpectedServer + N'.database.windows.net')
    THROW 51000, 'Wrong server. This check targets versalapps.database.windows.net.', 1;
IF OBJECT_ID(N'Migration.MigrationProjects', N'U') IS NULL
    THROW 51000, 'Migration Centre schema is missing. Review the deployed version.', 1;

-- RESULT 1: Confirm the connection.
SELECT N'1_CONNECTION' AS ResultSet,
       DB_NAME() AS DatabaseName,
       CONVERT(nvarchar(128),SERVERPROPERTY('ServerName')) AS ServerName,
       SYSDATETIMEOFFSET() AS CheckedAt;

-- RESULT 2: Project ID, state and exact settings to preserve.
-- Empty result: create the pilot project in /Migration first; do not invent a ProjectId.
SELECT N'2_PROJECTS' AS ResultSet, p.Id AS ProjectId, p.Name, p.SourceSystem,
       p.OpeningDate, p.ClosingDate, p.Currency, p.Status, p.Version,
       p.ApprovedHash, p.FinalizedAt,
       (SELECT COUNT_BIG(*) FROM Migration.MigrationUnits u
        WHERE u.ProjectId=p.Id AND u.Status=N'Posted') AS PostedUnits,
       (SELECT COUNT_BIG(*) FROM Migration.MigrationRuns r
        WHERE r.ProjectId=p.Id AND r.Status IN (N'Queued',N'Running')) AS ActiveRuns,
       ISJSON(p.SettingsJson) AS SettingsAreValidJson,
       p.SettingsJson
FROM Migration.MigrationProjects p ORDER BY p.Id;

-- RESULT 3: Relevant current run states. Do not change mappings during an active run.
SELECT N'3_RUNS' AS ResultSet, r.Id AS RunId, r.ProjectId, r.Status,
       r.CommittedUnits, r.CompletedAt, LEFT(r.Error,2000) AS Error
FROM Migration.MigrationRuns r
WHERE r.Status IN (N'Queued',N'Running',N'Failed')
ORDER BY r.Id DESC;

-- RESULT 4: Recent existing migration audit IDs; never reuse or overwrite these.
SELECT TOP (25) N'4_MIGRATION_AUDIT' AS ResultSet,
       a.Id AS AuditId, a.ProjectId, a.Action, a.CreatedAt, a.CreatedBy,
       LEFT(a.Detail,2000) AS Detail
FROM Migration.MigrationAudit a ORDER BY a.Id DESC;

-- RESULT 5: Verify identity/default/nullability for the future audit write.
-- An identity AuditId is generated by SQL Server; do not use MAX(Id)+1.
SELECT N'5_AUDIT_SCHEMA' AS ResultSet, s.name AS SchemaName, t.name AS TableName,
       c.column_id, c.name AS ColumnName, ty.name AS DataType,
       c.max_length AS MaxLengthBytes, c.is_nullable AS IsNullable,
       c.is_identity AS IsIdentity, dc.definition AS DefaultDefinition
FROM sys.tables t
JOIN sys.schemas s ON s.schema_id=t.schema_id
JOIN sys.columns c ON c.object_id=t.object_id
JOIN sys.types ty ON ty.user_type_id=c.user_type_id
LEFT JOIN sys.default_constraints dc ON dc.object_id=c.default_object_id
WHERE (s.name=N'Migration' AND t.name=N'MigrationAudit')
   OR (s.name=N'System' AND t.name=N'AuditLogs')
ORDER BY s.name,t.name,c.column_id;

